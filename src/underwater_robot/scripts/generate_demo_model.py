#!/usr/bin/env python3
"""Build an estimated, neutral-buoyancy demo without editing the CAD URDF.

CAD visual joints are frozen at their zero positions; this model demonstrates
vehicle control, not articulated-arm dynamics or measured vehicle performance.
"""
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET
from xml.dom.minidom import parseString
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
ALIGN = np.array([[1., 0., 0.], [0., 0., -1.], [0., 1., 0.]])


def vector(a):
    return ' '.join('%.12g' % x for x in a)


def transform(origin):
    t = np.eye(4)
    if origin is not None:
        t[:3, 3] = np.fromstring(origin.get('xyz', '0 0 0'), sep=' ')
        roll, pitch, yaw = np.fromstring(origin.get('rpy', '0 0 0'), sep=' ')
        cr, cp, cy = np.cos([roll, pitch, yaw]); sr, sp, sy = np.sin([roll, pitch, yaw])
        t[:3, :3] = [[cy*cp, cy*sp*sr-sy*cr, cy*sp*cr+sy*sr],
                     [sy*cp, sy*sp*sr+cy*cr, sy*sp*cr-cy*sr], [-sp, cp*sr, cp*cr]]
    return t


def rpy(r):
    return [np.arctan2(r[2, 1], r[2, 2]),
            np.arctan2(-r[2, 0], np.hypot(r[2, 1], r[2, 2])),
            np.arctan2(r[1, 0], r[0, 0])]


def text(parent, tag, value):
    ET.SubElement(parent, tag).text = str(value)


def inertial(link, mass, diagonal):
    node = ET.SubElement(link, 'inertial')
    ET.SubElement(node, 'origin', xyz='0 0 0', rpy='0 0 0')
    ET.SubElement(node, 'mass', value=str(mass))
    ET.SubElement(node, 'inertia', ixx=str(diagonal[0]), iyy=str(diagonal[1]),
                  izz=str(diagonal[2]), ixy='0', ixz='0', iyz='0')


def build():
    params = yaml.safe_load((ROOT/'config/demo_parameters.yaml').read_text())
    cfg = yaml.safe_load((ROOT/'config/thruster_manager.yaml').read_text())
    cad = ET.parse(ROOT/'urdf/underwater_robot.urdf').getroot()
    poses = {'base_link': np.eye(4)}
    pending = list(cad.findall('joint'))
    while pending:
        ready = [j for j in pending if j.find('parent').get('link') in poses]
        if not ready: raise ValueError('CAD joint graph is disconnected or cyclic')
        for j in ready:
            poses[j.find('child').get('link')] = poses[j.find('parent').get('link')] @ transform(j.find('origin'))
            pending.remove(j)
    root = ET.Element('robot', name='underwater_robot_demo', attrib={'xmlns:xacro': 'http://www.ros.org/wiki/xacro'})
    root.append(ET.Comment('GENERATED by generate_demo_model.py. ESTIMATED demo only; CAD visuals frozen.'))
    ET.SubElement(root, 'xacro:arg', name='namespace', default='underwater_robot')
    base = ET.SubElement(root, 'link', name='base_link')
    size = np.array(params['box_size']); mass = params['mass']
    inertia = mass/12 * np.array([size[1]**2+size[2]**2, size[0]**2+size[2]**2, size[0]**2+size[1]**2])
    inertial(base, mass, inertia)
    correction = np.eye(4); correction[:3, :3] = ALIGN
    correction[:3, 3] = -ALIGN @ np.array(params['cad_center'])
    for link in cad.findall('link'):
        for index, original in enumerate(link.findall('visual')):
            visual = deepcopy(original)
            visual.set('name', 'cad_%s_%d' % (link.get('name'), index))
            pose = correction @ poses[link.get('name')] @ transform(visual.find('origin'))
            origin = visual.find('origin')
            if origin is None: origin = ET.SubElement(visual, 'origin')
            origin.set('xyz', vector(pose[:3, 3])); origin.set('rpy', vector(rpy(pose[:3, :3])))
            material = visual.find('material')
            if material is not None: material.set('name', 'demo_%s_%d' % (link.get('name'), index))
            base.append(visual)
    collision = ET.SubElement(base, 'collision', name='demo_hull_collision')
    ET.SubElement(collision, 'origin', xyz='0.035 0 -0.015', rpy='0 0 0')
    ET.SubElement(ET.SubElement(collision, 'geometry'), 'box', size=vector(size))
    hydro = ET.SubElement(ET.SubElement(root, 'gazebo'), 'plugin', name='demo_hydrodynamics', filename='libuuv_underwater_object_ros_plugin.so')
    text(hydro, 'fluid_density', params['fluid_density'])
    text(hydro, 'flow_velocity_topic', 'hydrodynamics/current_velocity')
    hlink = ET.SubElement(hydro, 'link', name='base_link')
    text(hlink, 'neutrally_buoyant', 'true'); text(hlink, 'volume', mass/params['fluid_density'])
    text(hlink, 'center_of_buoyancy', vector(params['center_of_buoyancy']))
    model = ET.SubElement(hlink, 'hydrodynamic_model'); text(model, 'type', 'fossen')
    text(model, 'linear_damping', vector(-np.array(params['linear_damping'])))
    text(model, 'quadratic_damping', vector(-np.array(params['quadratic_damping'])))
    columns = []
    for i in range(6):
        item = cfg['thrusters']['thruster_%d' % i]
        pos = ALIGN @ (np.array(item['origin']) - np.array(params['cad_center']))
        direction = ALIGN @ np.array(item['direction']); direction /= np.linalg.norm(direction)
        link_name, joint_name = 'thruster_%d_link' % i, 'thruster_%d_joint' % i
        inertial(ET.SubElement(root, 'link', name=link_name), params['auxiliary_mass'], [1e-5]*3)
        joint = ET.SubElement(root, 'joint', name=joint_name, type='continuous')
        ET.SubElement(joint, 'parent', link='base_link'); ET.SubElement(joint, 'child', link=link_name)
        ET.SubElement(joint, 'origin', xyz=vector(pos), rpy='0 0 0'); ET.SubElement(joint, 'axis', xyz=vector(direction))
        sub = ET.SubElement(hydro, 'link', name=link_name)
        text(sub, 'neutrally_buoyant', 'true'); text(sub, 'volume', params['auxiliary_mass']/params['fluid_density'])
        text(sub, 'center_of_buoyancy', '0 0 0')
        submodel = ET.SubElement(sub, 'hydrodynamic_model'); text(submodel, 'type', 'fossen')
        plugin = ET.SubElement(ET.SubElement(root, 'gazebo'), 'plugin', name='demo_thruster_%d' % i, filename='libuuv_thruster_ros_plugin.so')
        for tag, value in [('linkName',link_name),('jointName',joint_name),('thrusterID',i)]: text(plugin,tag,value)
        dyn=ET.SubElement(plugin,'dynamics'); text(dyn,'type','FirstOrder'); text(dyn,'timeConstant',0.2)
        conv=ET.SubElement(plugin,'conversion'); text(conv,'type','Basic'); text(conv,'rotorConstant',params['conversion_gain'])
        columns.append(np.r_[direction,np.cross(pos,direction)])
    gazebo = ET.SubElement(root, 'gazebo')
    pose = ET.SubElement(gazebo, 'plugin', name='demo_pose_gt', filename='libuuv_gazebo_ros_pose_gt_plugin.so')
    for tag,value in [('robot_namespace','$(arg namespace)'),('link_name','base_link'),('sensor_topic','pose_gt'),('static_reference_frame','world'),('update_rate',30),('noise_sigma',0),('noise_amplitude',0),('publish_ned_odom','false'),('enable_gazebo_messages','false')]: text(pose,tag,value)
    joints=ET.SubElement(gazebo,'plugin',name='demo_joint_states',filename='libgazebo_ros_joint_state_publisher.so')
    text(joints,'robotNamespace','$(arg namespace)'); text(joints,'updateRate',30)
    text(joints,'jointName',','.join('thruster_%d_joint'%i for i in range(6)))
    b=np.column_stack(columns); u,s,vt=np.linalg.svd(b,full_matrices=False); s[s<1e-8]=0; b=(u*s)@vt
    manager={'thruster_manager':{'base_link':'base_link','tf_prefix':'underwater_robot','thruster_topic_prefix':'thruster_commands/','thruster_topic_suffix':'/input','thruster_frame_base':'thruster_','max_thrust':params['max_thrust'],'timeout':params['command_timeout'],'update_rate':30,'conversion_fcn':'proportional','conversion_fcn_params':{'gain':params['conversion_gain']}}}
    return parseString(ET.tostring(root)).toprettyxml(indent='  '), manager, {'tam':b.tolist()}


if __name__ == '__main__':
    model, config, tam = build()
    (ROOT/'urdf/underwater_robot_demo.xacro').write_text(model)
    (ROOT/'config/demo_thruster_manager.yaml').write_text(yaml.safe_dump(config,sort_keys=False))
    (ROOT/'config/demo_TAM.yaml').write_text(yaml.safe_dump(tam,sort_keys=False))
    print('Generated estimated demo model, configuration and rank-%d TAM' % np.linalg.matrix_rank(tam['tam'],tol=1e-8))
